def command_name(main, sub):
    name = _NAMES.get((main, sub))
    if name:
        return name
    return "%s_0x%02x" % (_GROUPS.get(main, "0x%02x" % main), sub)


def type_name(typ, tx):
    table = _TX_TYPES if tx else _RX_TYPES
    return table.get(typ, "0x%02x" % typ)


def is_known(main, sub):
    return (main, sub) in _NAMES
